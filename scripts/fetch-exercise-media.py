#!/usr/bin/env python3
"""Re-fetch exercise demonstration photos and instructions from Free Exercise DB.

Source: https://github.com/yuhonas/free-exercise-db (Unlicense / public domain).
Usage: python3 scripts/fetch-exercise-media.py   (requires Pillow and network access to GitHub)
It downloads both frames for every photo id referenced in src/shared/fitness/exercises.ts,
converts them to WebP (max 900 px wide) and regenerates src/shared/fitness/exercise-instructions.ts.
"""
import io, json, re, urllib.request
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BASE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/'
source = (ROOT / 'src/shared/fitness/exercises.ts').read_text()
ids = sorted(set(re.findall(r"photo: '([^']+)'", source)))
data = {e['id']: e for e in json.load(urllib.request.urlopen(BASE + 'dist/exercises.json'))}
out = ROOT / 'src/web/static/media/exercises'
out.mkdir(parents=True, exist_ok=True)
for exercise_id in ids:
    for n in (0, 1):
        raw = urllib.request.urlopen(BASE + 'exercises/' + data[exercise_id]['images'][n]).read()
        image = Image.open(io.BytesIO(raw)).convert('RGB')
        if image.width > 900:
            image = image.resize((900, round(image.height * 900 / image.width)))
        image.save(out / f'{exercise_id}-{n}.webp', 'WEBP', quality=74, method=6)
lines = ['// Step-by-step instructions from Free Exercise DB (github.com/yuhonas/free-exercise-db), released',
         '// into the public domain under the Unlicense. Generated by scripts/fetch-exercise-media.py; do not edit by hand.',
         'export const INSTRUCTIONS: Record<string, string[]> = {']
for exercise_id in ids:
    steps = [step.strip() for step in data[exercise_id]['instructions'] if step.strip()]
    lines.append(f'  {json.dumps(exercise_id)}: {json.dumps(steps, ensure_ascii=False)},')
(ROOT / 'src/shared/fitness/exercise-instructions.ts').write_text('\n'.join(lines + ['};', '']))
print(f'Fetched {len(ids)} exercises.')
